const DB_NAME = 'TypeOrDieDB_v1';
const DB_VERSION = 1;

export const STORE_PROFILES = 'profiles';
export const STORE_MATCHES = 'matches';

export function openDatabase(): Promise<IDBDatabase> {
  return new Promise((resolve, reject) => {
    const request = indexedDB.open(DB_NAME, DB_VERSION);

    request.onupgradeneeded = (event) => {
      const db = (event.target as IDBOpenDBRequest).result;

      // Profiles store
      if (!db.objectStoreNames.contains(STORE_PROFILES)) {
        const profileStore = db.createObjectStore(STORE_PROFILES, { keyPath: 'id' });
        profileStore.createIndex('name', 'name', { unique: true });
        profileStore.createIndex('wins', 'wins', { unique: false });
        profileStore.createIndex('highestWpm', 'highestWpm', { unique: false });
      }

      // Matches store
      if (!db.objectStoreNames.contains(STORE_MATCHES)) {
        const matchStore = db.createObjectStore(STORE_MATCHES, { keyPath: 'id' });
        matchStore.createIndex('timestamp', 'timestamp', { unique: false });
      }
    };

    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error);
  });
}

export async function dbGetAll<T>(storeName: string): Promise<T[]> {
  const db = await openDatabase();
  return new Promise((resolve, reject) => {
    const tx = db.transaction(storeName, 'readonly');
    const store = tx.objectStore(storeName);
    const request = store.getAll();

    request.onsuccess = () => resolve(request.result as T[]);
    request.onerror = () => reject(request.error);
  });
}

